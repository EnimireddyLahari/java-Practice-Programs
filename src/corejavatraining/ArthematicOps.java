package corejavatraining;

public class ArthematicOps {

	public static void main(String[] args) {
		int a=10;
		int b=20;
		int c=5;
		int d=15;
		int e=a+b;
		int f=c-d;
		int g=d*a;
		System.out.println(e);
		System.out.println(f);
		System.out.println(g);
		System.out.println(a/b);
		System.out.println(a%c);

	}

}
